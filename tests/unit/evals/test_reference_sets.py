"""The reference-set loaders, against synthetic files only.

Nothing here reads ``evals/reference_sets/``. Those files are curated by hand and
do not exist yet; a test that depended on them would either be skipped forever or
would tempt someone to generate them to make it pass.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from signaldesk.evals.signals.reference import (
    EXPECTED_ROWS,
    Label,
    ReferenceSetError,
    load_all,
    load_outcome_map,
    load_reference_set,
    missing_files,
)

pytestmark = pytest.mark.unit

HEADER = "drug_name,ingredient_rxcui,outcome_id,label,source_note\n"

MAP = """\
acute_renal_failure:
  # OMOP HOI definition, Ryan et al. 2013, Drug Saf 36(Suppl 1):S33-47
  pts:
    - "Acute kidney injury"
    - "Renal failure"
acute_liver_injury:
  # EU-ADR event definition, Coloma et al. 2013
  pts:
    - "Hepatic failure"
"""


def _write_set(root: Path, name: str, rows: list[str]) -> Path:
    path = root / f"{name}.csv"
    path.write_text(HEADER + "".join(rows), encoding="utf-8")
    return path


def _rows(positives: int, negatives: int) -> list[str]:
    rows = [
        f"drug{index},{1000 + index},acute_renal_failure,positive,note\n"
        for index in range(positives)
    ]
    rows += [
        f"other{index},{2000 + index},acute_liver_injury,negative,note\n"
        for index in range(negatives)
    ]
    return rows


@pytest.fixture
def root(tmp_path: Path) -> Path:
    (tmp_path / "outcome_pt_map.yaml").write_text(MAP, encoding="utf-8")
    for name, (positives, negatives) in EXPECTED_ROWS.items():
        _write_set(tmp_path, name, _rows(positives, negatives))
    return tmp_path


def test_a_complete_set_loads_with_its_published_counts(root: Path) -> None:
    outcome_map, sets = load_all(root)

    assert set(sets) == set(EXPECTED_ROWS)
    assert sets["harpaz_2013"].positives == 62
    assert sets["harpaz_2013"].negatives == 75
    assert sets["omop"].positives == 165
    assert sets["euadr"].negatives == 50
    assert "acute_renal_failure" in outcome_map


def test_preferred_terms_are_folded_for_comparison(root: Path) -> None:
    """The contingency builder emits upper-trimmed terms; the map must match."""
    outcome_map = load_outcome_map(root)

    assert outcome_map["acute_renal_failure"] == frozenset({"ACUTE KIDNEY INJURY", "RENAL FAILURE"})


def test_every_missing_file_is_named_at_once(tmp_path: Path) -> None:
    """Reporting one at a time would send a reader round the loop four times."""
    with pytest.raises(ReferenceSetError) as raised:
        load_all(tmp_path)

    message = str(raised.value)
    for name in ("outcome_pt_map.yaml", "harpaz_2013.csv", "omop.csv", "euadr.csv"):
        assert name in message
    assert "never generated by this project" in message
    assert len(missing_files(tmp_path)) == 4


def test_a_partial_set_still_names_only_what_is_absent(root: Path) -> None:
    (root / "omop.csv").unlink()

    assert [path.name for path in missing_files(root)] == ["omop.csv"]
    with pytest.raises(ReferenceSetError, match=r"omop\.csv"):
        load_all(root)


def test_a_lost_row_is_refused_rather_than_reported(root: Path) -> None:
    """A truncated standard moves every metric derived from it.

    This is the check that stops an AUROC being published against 60 positives
    while the caption says 62.
    """
    _write_set(root, "harpaz_2013", _rows(61, 75))

    with pytest.raises(ReferenceSetError, match="61 positive"):
        load_reference_set("harpaz_2013", root)


def test_an_unrecognised_label_is_refused(root: Path) -> None:
    _write_set(root, "euadr", [*_rows(43, 49), "x,3000,acute_liver_injury,unknown,note\n"])

    with pytest.raises(ReferenceSetError, match="is not recognised"):
        load_reference_set("euadr", root)


def test_an_outcome_absent_from_the_map_is_refused(root: Path) -> None:
    """Silently skipping it would shrink the reference set with no trace."""
    _write_set(root, "euadr", [*_rows(43, 49), "x,3000,pancreatitis,negative,note\n"])
    outcome_map = load_outcome_map(root)

    with pytest.raises(ReferenceSetError, match="has no entry in"):
        load_reference_set("euadr", root, outcome_map=outcome_map)


def test_a_blank_rxcui_is_recorded_not_dropped(root: Path) -> None:
    """An unmappable drug is a reported exclusion, not a missing row."""
    _write_set(root, "euadr", [*_rows(43, 49), "unmapped,,acute_liver_injury,negative,note\n"])
    reference = load_reference_set("euadr", root)

    unmapped = [pair for pair in reference.pairs if not pair.mappable]
    assert len(reference) == 93
    assert len(unmapped) == 1
    assert unmapped[0].drug_name == "unmapped"
    assert unmapped[0].label is Label.NEGATIVE


def test_a_non_integer_rxcui_is_refused(root: Path) -> None:
    _write_set(root, "euadr", [*_rows(43, 49), "x,RX1234,acute_liver_injury,negative,note\n"])

    with pytest.raises(ReferenceSetError, match="is not an integer"):
        load_reference_set("euadr", root)


def test_a_missing_column_is_refused(root: Path) -> None:
    (root / "omop.csv").write_text("drug_name,label\nx,positive\n", encoding="utf-8")

    with pytest.raises(ReferenceSetError, match="missing required columns"):
        load_reference_set("omop", root)


def test_an_entry_without_terms_is_refused(root: Path) -> None:
    (root / "outcome_pt_map.yaml").write_text("acute_renal_failure:\n  pts: []\n", encoding="utf-8")

    with pytest.raises(ReferenceSetError, match="empty or non-list"):
        load_outcome_map(root)


def test_an_empty_map_is_refused(root: Path) -> None:
    (root / "outcome_pt_map.yaml").write_text("\n", encoding="utf-8")

    with pytest.raises(ReferenceSetError, match="non-empty YAML mapping"):
        load_outcome_map(root)


def test_an_unknown_reference_set_name_is_refused(root: Path) -> None:
    with pytest.raises(ReferenceSetError, match="unknown reference set"):
        load_reference_set("made_up", root)
