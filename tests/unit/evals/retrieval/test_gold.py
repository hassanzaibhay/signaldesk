"""The gold-set loader, and every way it refuses.

There is no gold set. This suite exists to keep it that way until a person makes
one: the loader is the only thing standing between an empty `evals/golden/` and
a published recall figure, and every refusal below is a way that could have gone
wrong quietly.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import pytest

from signaldesk.evals.retrieval.gold import (
    GOLD_SET_FILENAME,
    RetrievalGoldSetError,
    default_gold_path,
    gold_root,
    load_gold_set,
    missing_reason,
    parse_judgements,
    relevant_ids,
)

pytestmark = pytest.mark.unit

FIXTURE = Path(__file__).resolve().parents[3] / "fixtures" / "retrieval" / "gold_sample.jsonl"


def _sha(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _line(query_id: str = "q1", **overrides: object) -> str:
    import json

    record: dict[str, object] = {
        "query_id": query_id,
        "query": "does metformin cause lactic acidosis",
        "relevant": [_sha("chunk-one")],
    }
    record.update(overrides)
    return json.dumps(record)


class TestTheFixtureGuard:
    """The mechanical half of "a fixture is not a gold set".

    A comment saying the fixture is unreachable is a claim. These are the tests
    that make it true, and that break if a later change points the loader at a
    fixture path.
    """

    def test_the_fixture_is_well_formed_and_non_empty(self) -> None:
        """Established first, so the refusal below cannot be passing for another reason."""
        judgements = parse_judgements(FIXTURE.read_text(encoding="utf-8").splitlines())

        assert len(judgements) == 2
        assert judgements[0].query_id == "q001"

    def test_the_loader_refuses_that_same_file_because_of_where_it_lives(self) -> None:
        """Well-formed, non-empty, and outside evals/golden. Still refused."""
        with pytest.raises(RetrievalGoldSetError, match="outside it"):
            load_gold_set(FIXTURE)

    def test_the_refusal_names_the_only_permitted_directory(self) -> None:
        with pytest.raises(RetrievalGoldSetError) as caught:
            load_gold_set(FIXTURE)

        message = str(caught.value)
        assert str(gold_root().resolve()) in message
        assert "parse_judgements" in message

    def test_a_path_that_escapes_upward_is_refused(self) -> None:
        """Resolution happens before the check, so traversal does not get past it."""
        escaping = (
            gold_root() / ".." / ".." / "tests" / "fixtures" / "retrieval" / "gold_sample.jsonl"
        )

        with pytest.raises(RetrievalGoldSetError, match="outside it"):
            load_gold_set(escaping)


class TestTheAbsentGoldSet:
    def test_there_is_no_gold_set_committed(self) -> None:
        """If this ever fails, a gold set appeared and this suite needs revisiting."""
        assert not default_gold_path().exists()

    def test_the_default_path_is_under_evals_golden(self) -> None:
        assert default_gold_path().parent == gold_root()
        assert default_gold_path().name == GOLD_SET_FILENAME

    def test_loading_it_refuses_with_the_schema(self) -> None:
        with pytest.raises(RetrievalGoldSetError) as caught:
            load_gold_set()

        message = str(caught.value)
        assert "is required and is absent" in message
        assert "query_id" in message
        assert "relevant" in message
        assert "never generated by this project" in message

    def test_missing_reason_reports_without_raising(self) -> None:
        assert "is required and is absent" in (missing_reason() or "")

    def test_an_empty_file_is_a_placeholder_not_a_gold_set_of_zero(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """Zero queries and no evaluation are the same state and it is not scored."""
        root = tmp_path / "golden"
        root.mkdir()
        (root / GOLD_SET_FILENAME).write_text("   \n\n", encoding="utf-8")
        monkeypatch.setattr("signaldesk.evals.retrieval.gold.gold_root", lambda: root)

        with pytest.raises(RetrievalGoldSetError, match="exists and is empty"):
            load_gold_set()

    def test_a_well_formed_file_in_the_right_place_loads(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The loader is not merely broken; it works when the file is real."""
        root = tmp_path / "golden"
        root.mkdir()
        (root / GOLD_SET_FILENAME).write_text(_line() + "\n", encoding="utf-8")
        monkeypatch.setattr("signaldesk.evals.retrieval.gold.gold_root", lambda: root)

        gold = load_gold_set()

        assert len(gold) == 1
        assert next(iter(gold)).query_id == "q1"


class TestParsing:
    def test_blank_lines_are_skipped(self) -> None:
        assert len(parse_judgements([_line("q1"), "", "  ", _line("q2")])) == 2

    def test_a_note_is_optional(self) -> None:
        assert parse_judgements([_line()])[0].note == ""

    @pytest.mark.parametrize("field", ["query_id", "query", "relevant"])
    def test_every_required_field_is_required(self, field: str) -> None:
        import json

        record = json.loads(_line())
        del record[field]

        with pytest.raises(RetrievalGoldSetError, match=field):
            parse_judgements([json.dumps(record)])

    def test_malformed_json_names_its_line_number(self) -> None:
        """A hand-curated file is fixed by hand; the line number is the fix."""
        with pytest.raises(RetrievalGoldSetError, match="line 2"):
            parse_judgements([_line("q1"), "{not json"])

    def test_a_non_object_line_is_refused(self) -> None:
        with pytest.raises(RetrievalGoldSetError, match="expected a JSON object"):
            parse_judgements(['["a", "b"]'])

    def test_a_blank_query_is_refused(self) -> None:
        with pytest.raises(RetrievalGoldSetError, match="query is blank"):
            parse_judgements([_line(query="   ")])

    def test_a_blank_query_id_is_refused(self) -> None:
        with pytest.raises(RetrievalGoldSetError, match="query_id is blank"):
            parse_judgements([_line(query_id="  ")])

    def test_a_duplicate_query_id_is_refused(self) -> None:
        """One query's judgements would otherwise replace another's in silence."""
        with pytest.raises(RetrievalGoldSetError, match="already appeared"):
            parse_judgements([_line("q1"), _line("q1")])

    def test_a_query_with_no_relevant_chunk_is_refused(self) -> None:
        """It has no defined recall and would drag the mean down like a failure."""
        with pytest.raises(RetrievalGoldSetError, match="non-empty list"):
            parse_judgements([_line(relevant=[])])

    @pytest.mark.parametrize(
        "value",
        ["not-a-hash", "ABC123", 12345, _sha("x")[:63], _sha("x").upper()],
    )
    def test_anything_that_is_not_a_chunk_sha256_is_refused(self, value: object) -> None:
        """Row ids change between rebuilds; a hash of the text does not."""
        with pytest.raises(RetrievalGoldSetError, match="is not a chunk sha256"):
            parse_judgements([_line(relevant=[value])])

    def test_a_file_of_only_blank_lines_parses_to_nothing_and_is_refused(self) -> None:
        with pytest.raises(RetrievalGoldSetError, match="zero judgements"):
            parse_judgements(["", "   "])

    def test_relevant_ids_collects_across_judgements(self) -> None:
        judgements = parse_judgements(FIXTURE.read_text(encoding="utf-8").splitlines())

        assert len(relevant_ids(judgements)) == 3
