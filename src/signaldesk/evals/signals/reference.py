"""Loading the published reference standards, strictly.

Three reference sets and one mapping file, all under ``evals/reference_sets/``,
all curated by hand. **Nothing in this module writes to those files, and nothing
in this project may generate them.** A reference standard produced by the system
it is meant to evaluate measures nothing.

The loaders are deliberately unforgiving. A missing file, an unrecognised label,
an ``outcome_id`` with no entry in the map: each raises and names the path and
the fix. The alternative - skipping the bad row - produces an AUROC computed on
a silently smaller reference set, which is the single most misleading number
this project could publish.

## The files

``harpaz_2013.csv``, ``omop.csv``, ``euadr.csv``, each::

    drug_name,ingredient_rxcui,outcome_id,label,source_note
    lisinopril,29046,acute_renal_failure,positive,"Harpaz 2013 Table 2"

* ``label`` is exactly ``positive`` or ``negative``.
* ``ingredient_rxcui`` is an RxNorm ``IN``/``PIN`` code. **Blank is meaningful**:
  it records a reference drug that could not be mapped. Such rows are excluded
  from the metric and counted in the exclusion report, never dropped quietly.
* ``outcome_id`` is a key into ``outcome_pt_map.yaml``, lowercase snake case.
* ``source_note`` is free text saying where the judgement came from.

``outcome_pt_map.yaml``::

    acute_renal_failure:
      # OMOP HOI definition, Ryan et al. 2013, Drug Saf 36(Suppl 1):S33-47
      pts:
        - "Acute kidney injury"
        - "Renal failure"

PT strings are compared after ``upper(trim(...))``, which is the form the
contingency builder emits.
"""

from __future__ import annotations

import csv
from collections.abc import Iterator
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path

import yaml

from signaldesk.core.errors import SignalDeskError


class ReferenceSetError(SignalDeskError):
    """A reference set is missing, malformed, or inconsistent with the map."""


class Label(StrEnum):
    """The two judgements a reference standard makes about a pair."""

    POSITIVE = "positive"
    NEGATIVE = "negative"


#: The three published standards, and how many rows each should carry.
#: ARCHITECTURE section 8.3. The expected counts are asserted on load: a file
#: that has lost rows in transcription would otherwise change every metric with
#: nothing to say it had.
EXPECTED_ROWS = {
    "harpaz_2013": (62, 75),
    "omop": (165, 234),
    "euadr": (43, 50),
}

REQUIRED_COLUMNS = ("drug_name", "ingredient_rxcui", "outcome_id", "label", "source_note")


@dataclass(frozen=True, slots=True)
class ReferencePair:
    """One drug-outcome judgement from a published standard."""

    drug_name: str
    ingredient_rxcui: int | None
    outcome_id: str
    label: Label
    source_note: str

    @property
    def mappable(self) -> bool:
        """Whether the drug resolved to an RxNorm ingredient."""
        return self.ingredient_rxcui is not None


@dataclass(frozen=True, slots=True)
class ReferenceSet:
    """A published standard, as loaded."""

    name: str
    pairs: tuple[ReferencePair, ...]
    path: Path

    def __len__(self) -> int:
        return len(self.pairs)

    @property
    def positives(self) -> int:
        return sum(1 for pair in self.pairs if pair.label is Label.POSITIVE)

    @property
    def negatives(self) -> int:
        return sum(1 for pair in self.pairs if pair.label is Label.NEGATIVE)


@dataclass(frozen=True, slots=True)
class OutcomeMap:
    """Health outcome to its MedDRA preferred terms, folded for comparison."""

    terms: dict[str, frozenset[str]]
    path: Path

    def __contains__(self, outcome_id: str) -> bool:
        return outcome_id in self.terms

    def __getitem__(self, outcome_id: str) -> frozenset[str]:
        return self.terms[outcome_id]

    def __iter__(self) -> Iterator[str]:
        return iter(self.terms)


def reference_root() -> Path:
    """Where the curated files live. Not configurable: they are repository data."""
    return Path(__file__).resolve().parents[3].parent / "evals" / "reference_sets"


def _missing(path: Path, what: str, shape: str) -> ReferenceSetError:
    return ReferenceSetError(
        f"{what} is required and was not found at {path}. It is curated by hand and is "
        f"never generated by this project. Expected {shape}"
    )


def load_outcome_map(root: Path | None = None) -> OutcomeMap:
    """Load the outcome-to-PT mapping, or say precisely what is missing."""
    path = (root or reference_root()) / "outcome_pt_map.yaml"
    if not path.exists():
        raise _missing(
            path,
            "the outcome to MedDRA PT map",
            "a YAML mapping of outcome_id to a 'pts' list of preferred terms, one "
            "source citation comment per entry.",
        )

    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(document, dict) or not document:
        message = f"{path} must be a non-empty YAML mapping of outcome_id to its terms"
        raise ReferenceSetError(message)

    terms: dict[str, frozenset[str]] = {}
    for outcome_id, entry in document.items():
        if not isinstance(entry, dict) or "pts" not in entry:
            message = f"{path}: entry {outcome_id!r} must be a mapping carrying a 'pts' list"
            raise ReferenceSetError(message)
        pts = entry["pts"]
        if not isinstance(pts, list) or not pts:
            message = f"{path}: entry {outcome_id!r} has an empty or non-list 'pts'"
            raise ReferenceSetError(message)
        terms[str(outcome_id)] = frozenset(str(term).strip().upper() for term in pts)

    return OutcomeMap(terms=terms, path=path)


def load_reference_set(
    name: str,
    root: Path | None = None,
    *,
    outcome_map: OutcomeMap | None = None,
    check_counts: bool = True,
) -> ReferenceSet:
    """Load one standard, validating every row against the schema and the map."""
    if name not in EXPECTED_ROWS:
        message = f"unknown reference set {name!r}; expected one of {sorted(EXPECTED_ROWS)}"
        raise ReferenceSetError(message)

    path = (root or reference_root()) / f"{name}.csv"
    if not path.exists():
        positives, negatives = EXPECTED_ROWS[name]
        raise _missing(
            path,
            f"the {name} reference set",
            f"a CSV with columns {', '.join(REQUIRED_COLUMNS)} and "
            f"{positives + negatives} rows ({positives} positive, {negatives} negative).",
        )

    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        missing = set(REQUIRED_COLUMNS) - set(reader.fieldnames or ())
        if missing:
            message = f"{path} is missing required columns: {', '.join(sorted(missing))}"
            raise ReferenceSetError(message)
        pairs = tuple(_row(path, number, row, outcome_map) for number, row in enumerate(reader, 2))

    reference = ReferenceSet(name=name, pairs=pairs, path=path)
    if check_counts:
        _check_counts(reference)
    return reference


def _row(
    path: Path, number: int, row: dict[str, str], outcome_map: OutcomeMap | None
) -> ReferencePair:
    raw_label = (row["label"] or "").strip().lower()
    try:
        label = Label(raw_label)
    except ValueError as error:
        message = (
            f"{path}:{number}: label {row['label']!r} is not recognised; "
            f"it must be exactly 'positive' or 'negative'"
        )
        raise ReferenceSetError(message) from error

    outcome_id = (row["outcome_id"] or "").strip()
    if not outcome_id:
        message = f"{path}:{number}: outcome_id is blank"
        raise ReferenceSetError(message)
    if outcome_map is not None and outcome_id not in outcome_map:
        message = (
            f"{path}:{number}: outcome_id {outcome_id!r} has no entry in "
            f"{outcome_map.path}. Add its MedDRA PT list there, with a source citation."
        )
        raise ReferenceSetError(message)

    # Blank is a recorded judgement - this drug could not be mapped - and is
    # carried through to the exclusion report rather than being turned into a
    # guess or dropped.
    raw_rxcui = (row["ingredient_rxcui"] or "").strip()
    if raw_rxcui:
        try:
            rxcui: int | None = int(raw_rxcui)
        except ValueError as error:
            message = f"{path}:{number}: ingredient_rxcui {raw_rxcui!r} is not an integer"
            raise ReferenceSetError(message) from error
    else:
        rxcui = None

    return ReferencePair(
        drug_name=(row["drug_name"] or "").strip(),
        ingredient_rxcui=rxcui,
        outcome_id=outcome_id,
        label=label,
        source_note=(row["source_note"] or "").strip(),
    )


def _check_counts(reference: ReferenceSet) -> None:
    positives, negatives = EXPECTED_ROWS[reference.name]
    if (reference.positives, reference.negatives) != (positives, negatives):
        message = (
            f"{reference.path} carries {reference.positives} positive and "
            f"{reference.negatives} negative rows; the published standard has "
            f"{positives} and {negatives}. A reference set that has lost rows moves "
            "every metric derived from it, so this is refused rather than reported."
        )
        raise ReferenceSetError(message)


def missing_files(root: Path | None = None) -> tuple[Path, ...]:
    """Every curated file that does not exist yet."""
    base = root or reference_root()
    candidates = [base / "outcome_pt_map.yaml"]
    candidates.extend(base / f"{name}.csv" for name in EXPECTED_ROWS)
    return tuple(path for path in candidates if not path.exists())


def load_all(root: Path | None = None) -> tuple[OutcomeMap, dict[str, ReferenceSet]]:
    """The map and all three standards, validated against each other.

    Every absent file is reported at once. Failing on the first one would send a
    reader to write a single file and run again, four times over.
    """
    absent = missing_files(root)
    if absent:
        base = root or reference_root()
        lines = [
            "the reference standards are required and are missing. They are curated by",
            "hand and are never generated by this project. Needed under",
            f"{base}:",
            "",
        ]
        for path in absent:
            if path.name == "outcome_pt_map.yaml":
                lines.append(
                    "  outcome_pt_map.yaml - YAML mapping each outcome_id to a 'pts' list "
                    "of MedDRA preferred terms, one source citation comment per entry"
                )
            else:
                positives, negatives = EXPECTED_ROWS[path.stem]
                lines.append(
                    f"  {path.name} - CSV, columns {', '.join(REQUIRED_COLUMNS)}; "
                    f"{positives + negatives} rows ({positives} positive, {negatives} "
                    "negative); label is exactly 'positive' or 'negative'; a blank "
                    "ingredient_rxcui records a drug that could not be mapped and is "
                    "excluded and counted, not dropped"
                )
        raise ReferenceSetError("\n".join(lines))

    outcome_map = load_outcome_map(root)
    sets = {name: load_reference_set(name, root, outcome_map=outcome_map) for name in EXPECTED_ROWS}
    return outcome_map, sets
