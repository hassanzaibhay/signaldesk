"""Loading the retrieval gold set, strictly, and refusing when there is none.

There is no gold set. `evals/golden/` holds a `.gitkeep` and nothing else, P12
is deferred with zero verdicts, and a relevance judgement is a human judgement:
a gold set produced by the system it evaluates, or by a model standing in for an
annotator, measures nothing at all. **Nothing in this module writes to that
directory and nothing in this project may generate its contents.**

So the harness ships complete and unrun, and this loader is what keeps it that
way. It refuses on an absent file, a present but empty one, zero parsed
judgements, a malformed line, and a judgement naming no relevant chunk. It never
scores a silently smaller set, because a recall figure computed over the subset
that happened to parse is the single most misleading number this part of the
project could produce.

## Where the file must live

`load_gold_set` reads only from `evals/golden/`. A path outside it is refused
even when the file is well-formed and non-empty. That rule exists because the
test fixtures are well-formed and non-empty by design: without the check, the
only thing standing between a fixture and a published metric is a convention,
and this project has found conventions wrong often enough to prefer a guard.
`parse_judgements` is the unguarded entry point tests use, and it takes lines
rather than a path so that it cannot read anything at all.

## The format

`retrieval_v1.jsonl`, one JSON object per line::

    {"query_id": "q001",
     "query": "does metformin cause lactic acidosis",
     "relevant": ["3b5d7ee3...64 hex chars..."],
     "note": "curated from the boxed warning"}

* `relevant` holds chunk `sha256` values, not database ids. A chunk's row id is
  assigned by whichever rebuild inserted it and means nothing across rebuilds;
  its hash is a function of its text and its section and is stable. A gold set
  keyed on row ids would silently point at different text after a reindex.
* Relevance is binary. Graded judgements would be a `retrieval_v2` schema, not
  an optional field here: a file where some rows carry grades and some do not
  is two datasets that average together into neither.
* `note` is free text recording where the judgement came from.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from pathlib import Path

from signaldesk.core.errors import SignalDeskError

#: Repository root: retrieval -> evals -> signaldesk -> src -> the repository.
REPO_ROOT = Path(__file__).resolve().parents[4]

#: The schema version this loader reads. A different schema is a different
#: filename, so an old file cannot be read under new rules by accident.
GOLD_SET_FILENAME = "retrieval_v1.jsonl"

_SHA256 = re.compile(r"^[0-9a-f]{64}$")

_REQUIRED = ("query_id", "query", "relevant")


class RetrievalGoldSetError(SignalDeskError):
    """The retrieval gold set is missing, empty, malformed, or out of place."""


@dataclass(frozen=True, slots=True)
class Judgement:
    """One query and the chunks a human judged relevant to it."""

    query_id: str
    query: str
    relevant: frozenset[str]
    note: str = ""


@dataclass(frozen=True, slots=True)
class GoldSet:
    """Every judgement in one file."""

    judgements: tuple[Judgement, ...]
    source: Path

    def __len__(self) -> int:
        return len(self.judgements)

    def __iter__(self) -> Iterable[Judgement]:
        return iter(self.judgements)


def gold_root() -> Path:
    """The only directory a gold set may be read from."""
    return REPO_ROOT / "evals" / "golden"


def default_gold_path() -> Path:
    """Where the curated gold set is expected."""
    return gold_root() / GOLD_SET_FILENAME


def _missing_message(path: Path) -> str:
    return "\n".join(
        [
            f"the retrieval gold set is required and is absent: {path}",
            "",
            "It is curated by hand and is never generated by this project. A",
            "relevance judgement produced by the system being evaluated, or by a",
            "model standing in for an annotator, measures nothing.",
            "",
            "The file is JSON Lines, one object per line:",
            "",
            '  {"query_id": "q001",',
            '   "query": "does metformin cause lactic acidosis",',
            '   "relevant": ["<64 hex characters, a label_chunk.sha256>"],',
            '   "note": "where this judgement came from"}',
            "",
            "  query_id  unique within the file",
            "  query     the text handed to the retriever",
            "  relevant  at least one chunk sha256; binary relevance",
            "  note      optional free text",
            "",
            "No retrieval metric is reported until this file exists.",
        ]
    )


def parse_judgements(lines: Iterable[str], *, source: str = "<lines>") -> tuple[Judgement, ...]:
    """Parse judgement lines, refusing on anything it cannot read exactly.

    Takes lines rather than a path, so it reads nothing and can be exercised on
    literals. Every refusal names the line number, because a malformed gold set
    is fixed by hand and "line 41" is the difference between a two-minute fix
    and a bisect.
    """
    judgements: list[Judgement] = []
    seen: set[str] = set()

    for number, raw in enumerate(lines, start=1):
        line = raw.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as error:
            message = f"{source} line {number}: not valid JSON ({error.msg})"
            raise RetrievalGoldSetError(message) from error
        if not isinstance(record, dict):
            message = f"{source} line {number}: expected a JSON object, got {type(record).__name__}"
            raise RetrievalGoldSetError(message)

        missing = [field for field in _REQUIRED if field not in record]
        if missing:
            message = f"{source} line {number}: missing required field(s) {', '.join(missing)}"
            raise RetrievalGoldSetError(message)

        query_id = str(record["query_id"]).strip()
        query = str(record["query"]).strip()
        if not query_id:
            message = f"{source} line {number}: query_id is blank"
            raise RetrievalGoldSetError(message)
        if not query:
            message = f"{source} line {number}: query is blank"
            raise RetrievalGoldSetError(message)
        if query_id in seen:
            message = (
                f"{source} line {number}: query_id {query_id!r} already appeared. "
                "Ids must be unique or one query's judgements silently replace another's."
            )
            raise RetrievalGoldSetError(message)

        relevant = record["relevant"]
        if not isinstance(relevant, list) or not relevant:
            message = (
                f"{source} line {number}: 'relevant' must be a non-empty list of chunk "
                "sha256 values. A query with no relevant chunk has no defined recall "
                "and would drag the mean down as though retrieval had failed."
            )
            raise RetrievalGoldSetError(message)
        for entry in relevant:
            if not isinstance(entry, str) or not _SHA256.match(entry):
                message = (
                    f"{source} line {number}: {entry!r} is not a chunk sha256 "
                    "(64 lowercase hex characters)"
                )
                raise RetrievalGoldSetError(message)

        seen.add(query_id)
        judgements.append(
            Judgement(
                query_id=query_id,
                query=query,
                relevant=frozenset(relevant),
                note=str(record.get("note", "")),
            )
        )

    if not judgements:
        message = (
            f"{source} parsed to zero judgements. An empty gold set is not an "
            "evaluation over nothing, it is an absent evaluation, and no metric "
            "is reported from it."
        )
        raise RetrievalGoldSetError(message)
    return tuple(judgements)


def load_gold_set(path: Path | None = None) -> GoldSet:
    """Read the curated gold set, or refuse and say exactly why.

    ``path`` exists for pointing at an alternative curated file, not for
    pointing at a fixture: anything outside ``evals/golden/`` is refused whether
    or not it parses.
    """
    resolved = (path or default_gold_path()).resolve()
    allowed = gold_root().resolve()
    if not resolved.is_relative_to(allowed):
        message = (
            f"refusing to read a gold set from {resolved}.\n"
            f"Gold sets are read only from {allowed}, and this path is outside it.\n"
            "Test fixtures are well-formed and non-empty by construction, so the "
            "location is the only thing distinguishing a curated judgement from a "
            "synthetic one. Use parse_judgements for fixtures; it reads no files."
        )
        raise RetrievalGoldSetError(message)

    if not resolved.is_file():
        raise RetrievalGoldSetError(_missing_message(resolved))

    text = resolved.read_text(encoding="utf-8")
    if not text.strip():
        message = (
            f"{resolved} exists and is empty. An empty file is not a gold set of "
            "zero queries; it is a placeholder, and no metric is computed from it."
        )
        raise RetrievalGoldSetError(message)

    return GoldSet(
        judgements=parse_judgements(text.splitlines(), source=str(resolved)), source=resolved
    )


def missing_reason(path: Path | None = None) -> str | None:
    """Why the gold set cannot be loaded, or None if it can.

    For callers that need to report the state without handling an exception,
    such as a status command.
    """
    try:
        load_gold_set(path)
    except RetrievalGoldSetError as error:
        return str(error)
    return None


def relevant_ids(judgements: Sequence[Judgement]) -> frozenset[str]:
    """Every chunk named by any judgement."""
    return frozenset().union(*(judgement.relevant for judgement in judgements))
